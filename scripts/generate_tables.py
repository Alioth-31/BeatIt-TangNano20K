"""Deterministic DDS tables; no recorded audio is used."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def generate():
    sine = [round(32767 * math.sin(2*math.pi*i/1024)) for i in range(1024)]
    (ROOT/'rtl/sine.hex').write_text(''.join(f'{v & 0xffff:04x}\n' for v in sine), encoding='ascii')
    init=['// Gowin DP 16-bit initialization, low address in least-significant bits.']
    for block in range(64):
        bits=sum((sine[block*16+i]&0xffff) << (i*16) for i in range(16))
        init.append(f", .INIT_RAM_{block:02X}(256'h{bits:064x})")
    (ROOT/'rtl/sine_dpb_init.vh').write_text('\n'.join(init)+'\n',encoding='ascii')
    notes = [60,62,64,65,67,69,71,72] + list(range(36,60))
    increments = [round(440*2**((n-69)/12)*2**32/48000) for n in notes]
    lines = ['// Generated by scripts/generate_tables.py; Fs=48000 Hz.',
        'function [31:0] note_increment;', '    input [4:0] key_id;', '    begin', '        case (key_id)']
    lines += [f"            5'd{i}: note_increment = 32'd{v}; // MIDI {notes[i]}" for i,v in enumerate(increments)]
    lines += ["            default: note_increment = 32'd39370534;", '        endcase', '    end', 'endfunction', '']
    (ROOT/'rtl/note_table.vh').write_text('\n'.join(lines), encoding='ascii')
    # MIDI pitch is separate from the legacy 32-entry source-ID mapping.
    midi_increments = [round(440*2**((n-69)/12)*2**32/48000) for n in range(128)]
    (ROOT/'rtl/midi_increment.hex').write_text(''.join(f'{v:08x}\n' for v in midi_increments), encoding='ascii')
    lines = ['// Generated by scripts/generate_tables.py; MIDI 0..127; Fs=48000 Hz.',
        'function [31:0] midi_note_increment;', '    input [6:0] midi_note;',
        '    begin', '        case (midi_note)']
    lines += [f"            7'd{n}: midi_note_increment = 32'd{v};" for n,v in enumerate(midi_increments)]
    lines += ["            default: midi_note_increment = 32'd39370534;", '        endcase', '    end', 'endfunction', '']
    (ROOT/'rtl/midi_note_table.vh').write_text('\n'.join(lines), encoding='ascii')
    factors = [round(65536*2**((i/16)/12)) for i in range(-32,33)]
    lines = ['// Index 0..64 = -2..+2 semitones in 1/16-semitone steps.',
        'function [16:0] bend_factor;', '    input [6:0] index;', '    begin', '        case (index)']
    lines += [f"            7'd{i}: bend_factor = 17'd{v};" for i,v in enumerate(factors)]
    lines += ["            default: bend_factor = 17'd65536;", '        endcase', '    end', 'endfunction', '']
    (ROOT/'rtl/bend_table.vh').write_text('\n'.join(lines), encoding='ascii')
    data = {'sample_rate':48000,'a4_increment':39370534,'notes':[{'key':i,'midi':n,'frequency':440*2**((n-69)/12),'increment':increments[i]} for i,n in enumerate(notes)]}
    (ROOT/'docs/tables.json').write_text(json.dumps(data, indent=2), encoding='utf-8')
    assert increments[5] == 39370534 and sine[256] == 32767 and sine[768] == -32767
    print('PASS deterministic tables; A4 increment = 39370534')
if __name__ == '__main__':
    generate()
